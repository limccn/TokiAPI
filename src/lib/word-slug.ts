/** Pick a uniform adjective-animal slug using one byte per word. */
export function generateWordSlug(): string {
  const bytes = new Uint8Array(2);
  crypto.getRandomValues(bytes);
  const adjective = SLUG_ADJECTIVES[bytes[0] ?? 0] ?? "brave";
  const animal = SLUG_ANIMALS[bytes[1] ?? 0] ?? "otter";
  return `${adjective}-${animal}`;
}
